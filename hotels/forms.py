# ────────────────────────────────────────────────────────────────────────────
# hotels/forms.py — форма загрузки файла для импорта отелей.
#
# Принимает CSV и Excel (.xlsx) — это единственные два формата, из которых
# практически имеет смысл ИМПОРТИРОВАТЬ структурированные табличные данные
# (строка = отель, колонка = поле). PDF и DOCX в этом проекте — форматы
# ТОЛЬКО для экспорта (см. hotels/exports.py): это документы для чтения
# человеком, а не для машинного разбора табличных данных обратно в БД —
# доставать из них таблицу отелей значительно сложнее и ненадёжнее, чем
# просто попросить экспортировать CSV/Excel из той системы, откуда
# переносится каталог.
# ────────────────────────────────────────────────────────────────────────────
from django import forms

ALLOWED_IMPORT_EXTENSIONS = ('.csv', '.xlsx')


class HotelImportForm(forms.Form):
    """
    Форма из одного поля: файл CSV или Excel с отелями.

    FileField — базовый механизм загрузки файла через форму. Сам файл на
    диск не сохраняется: он нужен только на время запроса, чтобы прочитать
    из него строки и создать объекты Hotel (см. hotels/views.py::import_hotels).
    """
    import_file = forms.FileField(
        label='Файл с отелями (CSV или Excel)',
        help_text=(
            'Колонки: name, city, address, price, rating. '
            'Первая строка — заголовок, она пропускается. '
            'Поддерживаются форматы .csv и .xlsx.'
        ),
    )

    def clean_import_file(self):
        file = self.cleaned_data['import_file']
        name = file.name.lower()
        if not name.endswith(ALLOWED_IMPORT_EXTENSIONS):
            raise forms.ValidationError(
                'Поддерживаются только файлы .csv и .xlsx.'
            )
        return file
