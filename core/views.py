# ────────────────────────────────────────────────────────────────────────────
# core/views.py — КОНТРОЛЛЕР приложения core (буква V в паттерне MVT).
# Задача view: получить запрос, взять нужные данные из моделей других
# приложений и отдать их в шаблон. Каждая строка ниже прокомментирована,
# чтобы её можно было объяснить студентам.
# ────────────────────────────────────────────────────────────────────────────

from django.shortcuts import render          # render() соединяет шаблон + данные и возвращает готовый HTTP-ответ
from hotels.models import Hotel              # импортируем модель отеля — core сам данных не хранит, берёт из hotels
from rooms.models import Room                # импортируем модель номера — данные для витрины берём из rooms


def home(request):                            # view-функция главной страницы; request — объект входящего запроса
    """
    Главная страница проекта.

    core — «объединяющее» приложение: оно не хранит своих данных, а собирает
    витрину из других приложений. Здесь мы показываем несколько лучших отелей
    и доступных номеров как превью, со ссылками в разделы Hotels и Rooms.
    """
    top_hotels = Hotel.objects.filter(is_active=True).order_by('-rating')[:3]   # 3 активных отеля с наибольшим рейтингом (минус = по убыванию)

    featured_rooms = (                        # начинаем формировать выборку номеров для витрины
        Room.objects                          # менеджер objects — точка входа ко всем запросам к таблице Room
        .on_sale()                            # оставляем только выставленные на продажу (аудит, дефект №4)
        .with_today_status()                  # + occupied_today для бейджа карточки (та же карточка, что и в rooms/списке)
        .select_related('hotel')              # сразу подгружаем связанный отель одним JOIN — экономим запросы к БД
        [:3]                                  # берём первые 3 записи (срез превращается в LIMIT 3 в SQL)
    )

    stats = {                                 # словарь с числами для блока статистики на главной
        'hotels': Hotel.objects.filter(is_active=True).count(),          # сколько всего активных отелей
        'rooms': Room.objects.on_sale().count(),                        # сколько всего номеров выставлено на продажу
        'cities': Hotel.objects.values('city').distinct().count(),       # сколько уникальных городов (distinct убирает повторы)
    }

    return render(request, 'core/home.html', {   # рендерим шаблон core/home.html, передавая ему контекст (данные ниже)
        'top_hotels': top_hotels,             # список топ-отелей -> доступен в шаблоне как {{ top_hotels }}
        'featured_rooms': featured_rooms,     # список номеров -> доступен в шаблоне как {{ featured_rooms }}
        'stats': stats,                       # словарь статистики -> в шаблоне {{ stats.hotels }} и т.д.
    })
