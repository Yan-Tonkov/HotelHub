# ────────────────────────────────────────────────────────────────────────────
# core/validators.py — общие валидаторы файлов для всего проекта.
#
# Занятие 2 «Файлы и мультимедиа»: расширение допустимо загружать не любой
# файл, а только определённые форматы и не любого размера — иначе на сервер
# попадут исполняемые файлы под видом картинки или слишком тяжёлые файлы,
# которые замедлят загрузку страницы.
#
# Валидаторы лежат в core, а не в hotels/rooms/users, потому что нужны
# сразу нескольким приложениям (обложка отеля, фото номера, аватар
# пользователя) — типичная задача для инфраструктурного «ядра» проекта.
# ────────────────────────────────────────────────────────────────────────────
from django.core.exceptions import ValidationError

# Разрешённые расширения изображений. FileExtensionValidator проверяет
# только расширение имени файла — этого достаточно для учебного проекта;
# для проверки содержимого файла использовали бы дополнительно Pillow.
ALLOWED_IMAGE_EXTENSIONS = ['jpg', 'jpeg', 'png', 'webp']


def validate_image_size(file, max_mb: int = 5) -> None:
    """
    Проверить, что загруженный файл не превышает max_mb мегабайт.

    file.size — атрибут Django UploadedFile, доступен ДО сохранения файла
    на диск, поэтому слишком тяжёлый файл отклоняется ещё на этапе
    валидации формы/модели, не попадая в MEDIA_ROOT.
    """
    limit_bytes = max_mb * 1024 * 1024
    if file.size > limit_bytes:
        raise ValidationError(f'Размер файла не должен превышать {max_mb} МБ.')
