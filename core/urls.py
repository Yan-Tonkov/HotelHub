# core/urls.py — таблица маршрутов приложения core.
# Сюда приходит запрос из config/urls.py (по include('core.urls')) и здесь
# сопоставляется адрес с конкретной view-функцией.
# ────────────────────────────────────────────────────────────────────────────

from django.urls import path                 # path() описывает один маршрут: шаблон адреса -> view
from . import views                          # импортируем views этого же приложения (точка = текущий пакет core)

app_name = 'core'                            # пространство имён приложения; в шаблонах ссылаемся как {% url 'core:home' %}

urlpatterns = [                              # список всех маршрутов приложения core
    path('', views.home, name='home'),       # пустой адрес '' = корень сайта -> вызывает views.home, имя маршрута 'home'
]
